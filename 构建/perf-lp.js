  '    else if (r === 8) { type = 15; ch = 0; amt = 2; desc = "使用「混沌魔方」获得 #" + (100 + (i % 500)) + " 2股"; }',
  '    else { type = 4; ch = -300; amt = 1; desc = "买入 #" + (100 + (i % 500)) + " 1 股"; }',
  '    return { k: "p" + i, t: t, v: { Id: i, LogTime: new Date(t).toISOString(), Type: type, Change: ch,',
  '      Amount: amt, RelatedId: 100 + (i % 500), Description: desc, Balance: 20000000 - (i % 1000000) } };',
  '  }',
  '  try {',
  '    var T = await waitT();',
  '    var nParam = 100000;',
  '    try {',
  '      var q = location.search.split("n=")[1];',
  '      if (q) nParam = Number(q.split("&")[0]);',
  '    } catch (e) {}',
  '    T.openLedger();',
  '    T.setRange("2000-01-01", "2030-01-01", "custom");',
  '    T.clearLocal();',
  '    await T.storeClear();',
  '    log("PERF n=" + nParam + " start mem=" + mem());',
  '    var t0 = performance.now();',
  '    var okBatches = 0;',
