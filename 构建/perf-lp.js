  '    else if (r === 4) { type = 14; ch = -100; amt = 0; desc = "个人所得税 100cc"; }',
  '    else if (r === 5) { type = 15; ch = 0; amt = -2; desc = "受到「虚空道标」攻击损失 #" + (100 + (i % 500)) + " 2股固定资产"; }',
